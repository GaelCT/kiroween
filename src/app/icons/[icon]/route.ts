export function generateStaticParams() {
  return Object.keys(icons).map((icon) => ({ icon }));
}

export async function GET(_request: Request, { params }: { params: Promise<{ icon: string }> }) {
  const { icon } = await params;
  const data = icons[icon];
  if (!data) return new Response(null, { status: 404 });
  const png = Buffer.from(data, "base64");
  return new Response(png, {
    headers: { "content-type": "image/png", "content-length": String(png.length), "cache-control": "public, max-age=3600" },
  });
}
